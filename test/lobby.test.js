const test = require('node:test');
const assert = require('node:assert/strict');
const { once } = require('node:events');
const { io: connect } = require('socket.io-client');
const { createLobby } = require('../server');

test('a room syncs, reserves and releases four phone slots', { timeout: 10000 }, async t => {
  const { io, server } = createLobby(300);
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  const origin = 'http://127.0.0.1:' + server.address().port;
  const clients = [];
  t.after(async () => {
    clients.forEach(client => client.close());
    await io.close();
  });
  async function client() {
    const socket = connect(origin, { forceNew: true });
    clients.push(socket);
    await once(socket, 'connect');
    return socket;
  }
  const host = await client();
  const { code, token } = await host.emitWithAck('create');
  assert.match(code, /^[A-Z]{4}$/);
  assert.equal((await fetch(origin + '/qr?url=' + origin + '/c/' + code)).headers.get('content-type'), 'image/png');
  await host.emitWithAck('enter', { host: true, code, token });
  const first = await client();
  assert.match((await first.emitWithAck('enter', { code: '????' })).error, /not found/);
  assert.match((await first.emitWithAck('enter', { host: true, code })).error, /access/);
  const identity = await first.emitWithAck('enter', { code, nickname: 'Alex' });
  async function joinPhone() {
    const phone = await client();
    const update = once(host, 'roster');
    const player = await phone.emitWithAck('enter', { code });
    return { player, phone, roster: (await update)[0] };
  }
  const second = await joinPhone();
  assert.equal(second.player.name, 'Player 2');
  assert.equal(second.roster.games[1].eligible, true);
  const tennisStarted = once(first, 'match');
  assert.equal((await host.emitWithAck('start', 'Table Tennis')).ok, true);
  const [tennis] = await tennisStarted;
  assert.equal(tennis.phase, 'calibration');
  first.emit('calibration', { id: tennis.id, step: 7 });
  const startBoth = once(first, 'match');
  host.emit('startCalibration', tennis.id);
  const [setup] = await startBoth;
  assert.equal(setup.calibrationStarted, true);
  assert.deepEqual(setup.players.map(p => p.step), [0, 0]);
  const oneReady = once(host, 'match');
  first.emit('calibration', { id: tennis.id, step: 7, slot: 1 });
  const [waiting] = await oneReady;
  assert.equal(waiting.phase, 'calibration');
  assert.deepEqual(waiting.players.map(p => p.step), [7, 0]);
  const bothReady = once(host, 'match');
  second.phone.emit('calibration', { id: tennis.id, step: 7 });
  assert.deepEqual((await bothReady)[0].players.map(p => p.step), [7, 7]);
  assert.equal((await once(host, 'match'))[0].phase, 'playing');
  const stroke = once(host, 'stroke');
  first.emit('input', { id: tennis.id, lane: -1, swing: true });
  assert.equal((await stroke)[0].slot, 0);
  const tennisEnd = once(first, 'match');
  host.emit('frame', { id: tennis.id, state: { winner: 0 } });
  assert.equal((await tennisEnd)[0].phase, 'results');
  const third = await joinPhone();
  assert.equal(third.roster.games[0].eligible, true);
  assert.equal(third.roster.games[1].eligible, true);
  assert.match((await host.emitWithAck('start', 'Table Tennis')).error, /Choose two/);
  assert.ok((await host.emitWithAck('start', { game: 'Table Tennis', slots: [2, 2] })).error);
  const pairStarted = once(first, 'match');
  assert.ok((await host.emitWithAck('start', { game: 'Table Tennis', slots: [0, 2] })).ok);
  assert.deepEqual((await pairStarted)[0].players.map(p => p.slot), [0, 2]);
  const returned = once(first, 'match');
  host.emit('lobby');
  await returned;
  const pogoStarted = once(first, 'match');
  assert.equal((await host.emitWithAck('start', 'Pogo Race')).ok, true);
  const [pogo] = await pogoStarted;
  const routed = once(host, 'pump');
  first.emit('input', { id: pogo.id, round: 1, pump: true, slot: 2 });
  assert.deepEqual((await routed)[0], { id: pogo.id, slot: 0, round: 1 });
  const pogoEnded = once(first, 'match');
  host.emit('frame', { id: pogo.id, state: { phase: 'finished', winners: [0] } });
  assert.equal((await pogoEnded)[0].phase, 'results');
  assert.equal((await joinPhone()).roster.count, 4);
  const extra = await client();
  const join = data => extra.emitWithAck('enter', { code, ...data });
  assert.equal((await join()).error, 'Room full');
  let update = once(host, 'roster');
  first.disconnect();
  assert.equal((await update)[0].count, 3);
  assert.equal((await join()).error, 'Room full');
  assert.equal((await join({ token: identity.token })).name, 'Alex');
  assert.match((await extra.emitWithAck('start', 'Bumper Cars')).error, /access/);
  const started = once(extra, 'match');
  assert.equal((await host.emitWithAck('start', 'Bumper Cars')).ok, true);
  const [match] = await started;
  const input = once(host, 'drive');
  extra.emit('input', { id: match.id, x: 3, y: 4, boost: true });
  const [drive] = await input;
  assert.deepEqual(drive, { slot: 0, x: 0.6, y: 0.8, boost: true });
  const results = once(extra, 'match');
  host.emit('frame', { id: match.id, state: { tick: 3600, cars: [] } });
  assert.equal((await results)[0].phase, 'results');
  const rematch = once(extra, 'match');
  assert.equal((await host.emitWithAck('start', 'Bumper Cars')).ok, true);
  assert.equal((await rematch)[0].phase, 'playing');
  const exited = once(extra, 'match');
  host.emit('lobby');
  assert.equal((await exited)[0], null);
  update = once(host, 'roster');
  extra.disconnect();
  await update;
  const [expired] = await once(host, 'roster');
  assert.deepEqual(expired.players.map(p => p.slot), [1, 2, 3]);
  assert.equal((await joinPhone()).player.name, 'Player 1');
});
